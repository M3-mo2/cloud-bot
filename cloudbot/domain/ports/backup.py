"""The backup adapter's port.

The service orchestrates artifact format, validation and the restore verdict; the
adapter is the only module allowed to touch the database and the filesystem. It
exposes primitives, never policy.
"""

from __future__ import annotations

from datetime import datetime
from typing import Protocol

from cloudbot.domain.backup import BackupConfig, BackupFile, BackupSnapshot, DbProbe

class BackupStore(Protocol):
    #: True when the live database is Postgres (dumps are ``database.sql``).
    @property
    def is_postgres(self) -> bool: ...

    #: A dump of the live database and the counts of **that same snapshot**.
    async def snapshot(self) -> BackupSnapshot: ...

    #: Apply a dump of the live database and re-open it (no restart).
    async def install(self, data: bytes) -> None: ...

    #: A re-appliable safety copy of the live database; returns the path.
    async def safety_copy(self) -> str: ...

    #: Inspect arbitrary dump bytes without touching the live one.
    async def probe(self, data: bytes) -> DbProbe: ...

    async def schema_version(self) -> int: ...
    async def counts(self) -> dict[str, int]: ...

    # -- configuration (the "settings" scope) ------------------------------
    async def settings_export(self) -> dict: ...
    async def settings_import(self, payload: dict) -> None: ...
    #: The tables a settings restore owns. Nothing outside this set is written.
    def settings_tables(self) -> tuple[str, ...]: ...

    # -- schedule + files ---------------------------------------------------
    async def config(self) -> BackupConfig: ...
    async def save_config(self, config: BackupConfig, *, actor: int) -> None: ...
    async def files(self) -> list[BackupFile]: ...
    async def prune(self, keep: int) -> list[str]: ...
    def backup_dir(self) -> str: ...
    async def store(self, filename: str, data: bytes) -> str: ...
    #: Read a file **this feature owns** by name (for restoring an on-disk copy).
    async def read_owned(self, filename: str) -> bytes | None: ...
    async def pending_path(self, token: str, suffix: str) -> str: ...
    async def write_pending(self, token: str, suffix: str, data: bytes) -> str: ...
    async def read_pending(self, token: str, suffix: str) -> bytes: ...
    async def drop_pending(self, token: str, suffix: str) -> None: ...
